"""emoji 字符类：全插件唯一的一份。

`style_profile`（统计她平时爱不爱用 emoji）、`generator`（清洗模型输出）、
`groupflow`（群消息预筛里的「纯表情先筛掉」）原本各写了一份**逐字节等价**的正则，
还在注释里互相点名「与 X 同一套写法」——那恰恰说明它该只有一份：
改一处漏一处，漏的那处会静默改变行为（`groupflow` 那份漏改，「😀😀😀」就会
重新被当成有正文的群消息送进模型，而且测试全绿）。

范围取自 Unicode emoji 的常用区：
- `U+1F000–U+1FAFF`：绝大多数 emoji（表情、手势、旗帜、食物、交通…）
- `U+2600–U+27BF`：杂项符号与装饰符号（☀ ❤ ✨ …）
- `U+2B00–U+2BFF`：杂项符号与箭头（⭐ …）
- `U+FE0F`：变体选择符（把 ⌚ 这类文本型符号渲染成彩色 emoji）
- `U+200D`：零宽连接符（👨‍👩‍👧 这类组合）
- `U+20E3`：组合键帽（1️⃣）

值与原三份**完全一致**，去重不改行为。
"""

from __future__ import annotations

import re

#: emoji 与变体选择符的字符类（连续多个算一整段，用 `+` 合成一段再 `.sub` 掉）。
EMOJI = re.compile(
    "["
    "\U0001F000-\U0001FAFF"
    "\U00002600-\U000027BF"
    "\U00002B00-\U00002BFF"
    "\uFE0F\u200D\u20E3"
    "]+"
)
